async function writeTemplate(fileName, parts) {
  const zip = new ZipFile();
  for (const [zipPath, xml] of Object.entries(parts)) {
    zip.addBuffer(Buffer.from(xml, "utf8"), zipPath, {
      compress: false,
      mtime: fixedMtime,
    });
  }
  zip.end();

  const output = createWriteStream(new URL(fileName, templateDirectory));
  zip.outputStream.pipe(output);
  await finished(output);
}

await mkdir(fileURLToPath(templateDirectory), { recursive: true });
await Promise.all([
  writeTemplate("blank.docx", wordParts),
  writeTemplate("blank.xlsx", excelParts),
]);
